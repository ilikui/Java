CREATE TABLE stock_adjustment_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
    book_id BIGINT NOT NULL,
    old_total_copies INTEGER NOT NULL CHECK (old_total_copies >= 0),
    new_total_copies INTEGER NOT NULL CHECK (new_total_copies >= 0),
    old_available_copies INTEGER NOT NULL CHECK (old_available_copies >= 0),
    new_available_copies INTEGER NOT NULL CHECK (new_available_copies >= 0),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_adjustment_book FOREIGN KEY (book_id) REFERENCES books(id)
);

CREATE INDEX idx_stock_adjustment_book_time ON stock_adjustment_audit(book_id, occurred_at);
