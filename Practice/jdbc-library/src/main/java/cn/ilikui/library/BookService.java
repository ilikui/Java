package cn.ilikui.library;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

/** Business operations whose multi-statement changes must be atomic. */
public final class BookService {
    private final Connection connection;
    private final BookDao books;

    public BookService(Connection connection, BookDao books) throws SQLException {
        this.connection = Objects.requireNonNull(connection, "connection");
        this.books = Objects.requireNonNull(books, "books");
        try (Statement statement = connection.createStatement()) {
            statement.executeUpdate("CREATE TABLE IF NOT EXISTS book_stock (book_id BIGINT PRIMARY KEY REFERENCES books(id), available_count INT NOT NULL CHECK (available_count >= 0))");
            statement.executeUpdate("CREATE TABLE IF NOT EXISTS loans (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, book_id BIGINT NOT NULL REFERENCES books(id), borrower VARCHAR(120) NOT NULL, borrowed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, returned_at TIMESTAMP NULL)");
        }
    }

    public long register(Book book, int initialStock) throws SQLException {
        if (initialStock < 0) throw new IllegalArgumentException("initialStock must not be negative");
        return inTransaction(() -> {
            long id = books.create(book);
            try (PreparedStatement ps = connection.prepareStatement("INSERT INTO book_stock(book_id, available_count) VALUES (?, ?)")) {
                ps.setLong(1, id); ps.setInt(2, initialStock); ps.executeUpdate();
            }
            return id;
        });
    }

    public long borrow(long bookId, String borrower) throws SQLException {
        if (bookId <= 0) throw new IllegalArgumentException("bookId must be positive");
        if (borrower == null || borrower.isBlank()) throw new IllegalArgumentException("borrower must not be blank");
        String normalizedBorrower = borrower.trim();
        return inTransaction(() -> {
            if (books.findById(bookId).isEmpty()) throw new IllegalArgumentException("Book not found: " + bookId);
            try (PreparedStatement stock = connection.prepareStatement("UPDATE book_stock SET available_count = available_count - 1 WHERE book_id = ? AND available_count > 0")) {
                stock.setLong(1, bookId);
                if (stock.executeUpdate() != 1) throw new IllegalStateException("No copies available for book: " + bookId);
            }
            try (PreparedStatement loan = connection.prepareStatement("INSERT INTO loans(book_id, borrower) VALUES (?, ?)", Statement.RETURN_GENERATED_KEYS)) {
                loan.setLong(1, bookId); loan.setString(2, normalizedBorrower); loan.executeUpdate();
                try (ResultSet keys = loan.getGeneratedKeys()) {
                    if (!keys.next()) throw new SQLException("Database did not return loan id");
                    return keys.getLong(1);
                }
            }
        });
    }

    public void returnBook(long loanId) throws SQLException {
        if (loanId <= 0) throw new IllegalArgumentException("loanId must be positive");
        inTransaction(() -> {
            long bookId;
            try (PreparedStatement ps = connection.prepareStatement("SELECT book_id FROM loans WHERE id = ? AND returned_at IS NULL FOR UPDATE")) {
                ps.setLong(1, loanId);
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) throw new IllegalStateException("Active loan not found: " + loanId);
                    bookId = rs.getLong(1);
                }
            }
            try (PreparedStatement ps = connection.prepareStatement("UPDATE loans SET returned_at = CURRENT_TIMESTAMP WHERE id = ? AND returned_at IS NULL")) {
                ps.setLong(1, loanId);
                if (ps.executeUpdate() != 1) throw new IllegalStateException("Loan was already returned: " + loanId);
            }
            try (PreparedStatement ps = connection.prepareStatement("UPDATE book_stock SET available_count = available_count + 1 WHERE book_id = ?")) {
                ps.setLong(1, bookId);
                if (ps.executeUpdate() != 1) throw new SQLException("Stock row missing for book: " + bookId);
            }
            return null;
        });
    }

    /** Returns all loans for a book, oldest first; active loans have a null returnedAt. */
    public List<LoanRecord> findLoanHistory(long bookId) throws SQLException {
        if (bookId <= 0) throw new IllegalArgumentException("bookId must be positive");
        String sql = "SELECT id, book_id, borrower, borrowed_at, returned_at FROM loans WHERE book_id = ? ORDER BY id";
        List<LoanRecord> history = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setLong(1, bookId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    Timestamp borrowed = rs.getTimestamp("borrowed_at");
                    Timestamp returned = rs.getTimestamp("returned_at");
                    history.add(new LoanRecord(
                            rs.getLong("id"),
                            rs.getLong("book_id"),
                            rs.getString("borrower"),
                            borrowed == null ? null : borrowed.toLocalDateTime(),
                            returned == null ? null : returned.toLocalDateTime()));
                }
            }
        }
        return List.copyOf(history);
    }

    public int availableCopies(long bookId) throws SQLException {
        try (PreparedStatement ps = connection.prepareStatement("SELECT available_count FROM book_stock WHERE book_id = ?")) {
            ps.setLong(1, bookId);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) throw new IllegalArgumentException("Stock not found for book: " + bookId);
                return rs.getInt(1);
            }
        }
    }

    private <T> T inTransaction(SqlWork<T> work) throws SQLException {
        boolean originalAutoCommit = connection.getAutoCommit();
        Throwable primaryFailure = null;
        try {
            connection.setAutoCommit(false);
            T result = work.run();
            connection.commit();
            return result;
        } catch (SQLException | RuntimeException | Error ex) {
            primaryFailure = ex;
            try {
                connection.rollback();
            } catch (SQLException rollbackError) {
                ex.addSuppressed(rollbackError);
            }
            throw ex;
        } finally {
            try {
                connection.setAutoCommit(originalAutoCommit);
            } catch (SQLException restoreError) {
                if (primaryFailure != null) {
                    // Keep the business/SQL failure as primary; retain cleanup failure for diagnosis.
                    primaryFailure.addSuppressed(restoreError);
                } else {
                    throw restoreError;
                }
            }
        }
    }

    @FunctionalInterface private interface SqlWork<T> { T run() throws SQLException; }
}