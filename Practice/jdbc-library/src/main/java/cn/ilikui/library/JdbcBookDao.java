package cn.ilikui.library;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

public final class JdbcBookDao implements BookDao {
    private final Connection connection;

    public JdbcBookDao(Connection connection) throws SQLException {
        this.connection = java.util.Objects.requireNonNull(connection, "connection");
        try (Statement statement = connection.createStatement()) {
            statement.executeUpdate("CREATE TABLE IF NOT EXISTS books (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(200) NOT NULL, author VARCHAR(120) NOT NULL, price DECIMAL(12,2) NOT NULL CHECK (price >= 0))");
        }
    }

    @Override public long create(Book book) throws SQLException {
        String sql = "INSERT INTO books(title, author, price) VALUES (?, ?, ?)";
        try (PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, book.title()); ps.setString(2, book.author()); ps.setBigDecimal(3, book.price());
            if (ps.executeUpdate() != 1) throw new SQLException("Insert did not create exactly one row");
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (!keys.next()) throw new SQLException("Database did not return generated key");
                return keys.getLong(1);
            }
        }
    }

    @Override public Optional<Book> findById(long id) throws SQLException {
        String sql = "SELECT id, title, author, price FROM books WHERE id = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) { return rs.next() ? Optional.of(map(rs)) : Optional.empty(); }
        }
    }

    @Override public List<Book> findAll() throws SQLException {
        List<Book> books = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement("SELECT id, title, author, price FROM books ORDER BY id"); ResultSet rs = ps.executeQuery()) {
            while (rs.next()) books.add(map(rs));
        }
        return List.copyOf(books);
    }

    @Override public boolean update(Book book) throws SQLException {
        String sql = "UPDATE books SET title = ?, author = ?, price = ? WHERE id = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, book.title()); ps.setString(2, book.author()); ps.setBigDecimal(3, book.price()); ps.setLong(4, book.id());
            return ps.executeUpdate() == 1;
        }
    }

    @Override public boolean deleteById(long id) throws SQLException {
        try (PreparedStatement ps = connection.prepareStatement("DELETE FROM books WHERE id = ?")) {
            ps.setLong(1, id); return ps.executeUpdate() == 1;
        }
    }

    private static Book map(ResultSet rs) throws SQLException {
        return new Book(rs.getLong("id"), rs.getString("title"), rs.getString("author"), rs.getBigDecimal("price"));
    }
}